import React, { useEffect, useRef } from 'react';
import * as THREE from 'three';
import { OrbitControls, DragControls, TransformControls } from 'three-stdlib';

import {
  loadHouse,
  disposeHouse,
  disposeDracoLoader,
  createHouseMaterials,
  disposeHouseMaterials,
  HOUSE_VIEWS,
  LIVING_ZONE_CENTRE,
} from './house';
import { createAtmosphere } from './atmosphere/Atmosphere';

const CanvasContainer = ({ currentRoom, currentIndex, isAdmin }) => {
  const canvasRef = useRef(null);
  const sceneRef = useRef(null);
  const rendererRef = useRef(null);
  const cameraRef = useRef(null);
  const controlsRef = useRef(null);
  const furnitureRef = useRef(null);
  const gltfModelsGroupRef = useRef(null);
  const houseRef = useRef(null);
  const houseMaterialsRef = useRef(null);
  const atmosphereRef = useRef(null);

  useEffect(() => {
    if (!canvasRef.current) return;

    // Initialize Three.js scene
    let disposed = false;

    const scene = new THREE.Scene();
    // Background and fog are set by the atmosphere below, so the sky, the
    // fog and the cloud layers cannot drift out of agreement.

    const camera = new THREE.PerspectiveCamera(
      55,
      canvasRef.current.clientWidth / canvasRef.current.clientHeight,
      0.1,
      1000
    );

    const renderer = new THREE.WebGLRenderer({ antialias: true, alpha: true });
    renderer.setSize(canvasRef.current.clientWidth, canvasRef.current.clientHeight);
    renderer.shadowMap.enabled = true;
    renderer.shadowMap.type = THREE.PCFSoftShadowMap;
    renderer.outputColorSpace = THREE.SRGBColorSpace;
    renderer.toneMapping = THREE.ACESFilmicToneMapping;
    renderer.toneMappingExposure = 1;

    canvasRef.current.appendChild(renderer.domElement);

    // Orbit Controls
    const orbitControls = new OrbitControls(camera, renderer.domElement);
    orbitControls.enableDamping = true;
    orbitControls.dampingFactor = 0.05;
    orbitControls.screenSpacePanning = true;
    // The house is ~14m across, so the old 10m ceiling put the camera inside
    // the building at full zoom-out.
    orbitControls.minDistance = 1.5;
    orbitControls.maxDistance = 75;   // far enough to see the whole 30x40 yard
    orbitControls.maxPolarAngle = Math.PI / 2;
    orbitControls.enabled = true;

    // Store references
    sceneRef.current = scene;
    rendererRef.current = renderer;
    cameraRef.current = camera;
    controlsRef.current = orbitControls;

    // Materials for the placeholder furniture. The house brings its own --
    // see house/textures/materialLibrary.js.
    const materials = {
      sofaFabric: createSofaFabricMaterial(),
      woodDark: createWoodDarkMaterial(),
      woodLight: createWoodLightMaterial(),
      glass: createGlassMaterial(),
      metal: createMetalMaterial(),
      fabricRug: createRugMaterial(),
      plant: createPlantMaterial(),
      mirror: createMirrorMaterial(),
      tvScreen: createTVScreenMaterial()
    };

    // ---- Sky, clouds, fog ------------------------------------------------
    const atmosphere = createAtmosphere();
    atmosphere.applyTo(scene);
    atmosphereRef.current = atmosphere;

    // ---- The house and its yard ------------------------------------------
    // Loaded from the per-component GLBs generated by blender/houseluxe.
    // Textures are applied here, in three.js, keyed by Blender material name.
    const houseMaterials = createHouseMaterials({
      anisotropy: renderer.capabilities.getMaxAnisotropy(),
    });
    houseMaterialsRef.current = houseMaterials;

    loadHouse({ materials: houseMaterials })
      .then(({ house, errors, stats }) => {
        // The component can unmount while the GLBs are still in flight.
        if (disposed) {
          disposeHouse(house);
          return;
        }

        scene.add(house);
        houseRef.current = house;

        if (errors.length) {
          console.error(
            '[house] %d part(s) failed to load:',
            errors.length,
            errors.map((e) => `${e.file}: ${e.error?.message ?? e.error}`)
          );
        }
        if (stats.untextured.size) {
          console.warn(
            '[house] no three.js material for:',
            [...stats.untextured].join(', ')
          );
        }
      })
      .catch((error) => console.error('[house] failed to load:', error));

    // ---- Placeholder furniture -------------------------------------------
    // Primitive furniture, kept until the Blender-authored TVs and sofas
    // arrive. It was modelled for the old 12x10 room, so it is scaled and
    // parked in the open living/dining zone rather than left at the origin.
    const furniture = createFurniture(materials);
    furnitureRef.current = furniture;

    const gltfModelsGroup = new THREE.Group();
    gltfModelsGroupRef.current = gltfModelsGroup;

    const staging = new THREE.Group();
    staging.name = 'placeholder-furniture';
    staging.position.set(...LIVING_ZONE_CENTRE);
    staging.scale.setScalar(0.75);
    staging.add(furniture);
    staging.add(gltfModelsGroup);
    scene.add(staging);

    // Lighting setup
    setupLighting(scene, atmosphere.sunDirection);

    // Load GLTF models
    loadGLTFModels(gltfModelsGroup, furniture);

    // Setup TV video playback
    setupTVVideo(furniture);

    // Set initial camera position
    const view = HOUSE_VIEWS.overview;
    camera.position.set(...view.position);
    camera.lookAt(...view.target);
    orbitControls.target.set(...view.target);

    // Animation loop
    const clock = new THREE.Clock();
    const animate = () => {
      requestAnimationFrame(animate);
      const delta = clock.getDelta();

      orbitControls.update();
      atmosphere.update(delta);

      // Keep the sky centred on the viewer so it can never be reached.
      atmosphere.group.position.set(camera.position.x, 0, camera.position.z);

      renderer.render(scene, camera);
    };
    animate();

    // Handle resize
    const handleResize = () => {
      const width = canvasRef.current.clientWidth;
      const height = canvasRef.current.clientHeight;
      camera.aspect = width / height;
      camera.updateProjectionMatrix();
      renderer.setSize(width, height);
    };

    window.addEventListener('resize', handleResize);

    // Cleanup
    return () => {
      disposed = true;
      window.removeEventListener('resize', handleResize);

      disposeHouse(houseRef.current);
      disposeHouseMaterials(houseMaterialsRef.current);
      disposeDracoLoader();   // shuts down the decoder's Web Workers
      atmosphereRef.current?.dispose();
      houseRef.current = null;
      houseMaterialsRef.current = null;
      atmosphereRef.current = null;

      if (rendererRef.current && canvasRef.current) {
        canvasRef.current.removeChild(rendererRef.current.domElement);
        rendererRef.current.dispose();
      }
    };
  }, []);

  useEffect(() => {
    // Update canvas title based on current room and index
    const canvasTitle = document.getElementById('canvas-title');
    if (canvasTitle) {
      if (currentRoom === 'living-room') {
        canvasTitle.textContent = 'Living Room - Click furniture to explore';
      } else {
        canvasTitle.textContent = `Coming soon - ${currentRoom.replace('-', ' ').replace(/\b\w/g, l => l.toUpperCase())}`;
      }
    }
  }, [currentRoom, currentIndex]);

  return (
    <div id="canvas-container">
      <div className="canvas-overlay" id="canvas-title">Living Room - Click furniture to explore</div>
      <div className="rotation-indicator">
        <span className="rotation-icon">↻</span>
        <span id="rotation-text">360° View Active</span>
      </div>
      <div className="camera-controls">
        <div className="edit-controls">
          <button className="edit-btn" id="drag-mode" title="Drag Mode - Click and drag furniture" style={{ display: 'none' }}>✋</button>
          <button className="edit-btn" id="transform-mode" title="Transform Mode - Edit position/rotation/scale" style={{ display: isAdmin ? 'block' : 'none' }}>🔧</button>
        </div>
        <div className="transform-sub-controls" id="transform-sub-controls" style={{ display: 'none' }}>
          <button className="transform-sub-btn" id="translate-mode" title="Move">↔️</button>
          <button className="transform-sub-btn" id="rotate-mode" title="Rotate">🔄</button>
          <button className="transform-sub-btn" id="scale-mode" title="Scale">📏</button>
        </div>
        <button className="camera-btn" id="camera-front" title="Front View">👁️</button>
        <button className="camera-btn" id="camera-side" title="Side View">👈</button>
        <button className="camera-btn" id="camera-top" title="Top View">⬇️</button>
        <button className="camera-btn" id="camera-reset" title="Reset View">🔄</button>
      </div>
      <div ref={canvasRef} style={{ width: '100%', height: '100%' }}></div>
    </div>
  );
};

// Material creation functions
function createSofaFabricMaterial() {
  return new THREE.MeshStandardMaterial({
    color: 0x2c5f7a,
    roughness: 0.9
  });
}

function createWoodDarkMaterial() {
  return new THREE.MeshStandardMaterial({
    color: 0x4a3728,
    roughness: 0.5
  });
}

function createWoodLightMaterial() {
  return new THREE.MeshStandardMaterial({
    color: 0xd4b89c,
    roughness: 0.4
  });
}

function createGlassMaterial() {
  return new THREE.MeshPhysicalMaterial({
    color: 0xffffff,
    transparent: true,
    opacity: 0.2,
    roughness: 0.05,
    transmission: 0.95,
    thickness: 0.5
  });
}

function createMetalMaterial() {
  return new THREE.MeshStandardMaterial({
    color: 0xcccccc,
    roughness: 0.2,
    metalness: 0.9
  });
}

function createRugMaterial() {
  const canvas = document.createElement('canvas');
  canvas.width = 512;
  canvas.height = 512;
  const ctx = canvas.getContext('2d');

  ctx.fillStyle = '#8b4513';
  ctx.fillRect(0, 0, 512, 512);

  ctx.strokeStyle = '#d4a574';
  ctx.lineWidth = 20;
  ctx.strokeRect(50, 50, 412, 412);

  ctx.fillStyle = '#d4a574';
  ctx.beginPath();
  ctx.arc(256, 256, 80, 0, Math.PI * 2);
  ctx.fill();

  const texture = new THREE.CanvasTexture(canvas);
  texture.wrapS = THREE.RepeatWrapping;
  texture.wrapT = THREE.RepeatWrapping;
  return new THREE.MeshStandardMaterial({
    color: 0x8b4513,
    roughness: 0.9,
    map: texture
  });
}

function createPlantMaterial() {
  return new THREE.MeshStandardMaterial({
    color: 0x3d6b3d,
    roughness: 0.8
  });
}

function createMirrorMaterial() {
  return new THREE.MeshStandardMaterial({
    color: 0x888888,
    roughness: 0.05,
    metalness: 0.95
  });
}

function createTVScreenMaterial() {
  return new THREE.MeshStandardMaterial({
    color: 0xffffff,
    roughness: 0.1,
    emissive: 0x222222,
    emissiveIntensity: 0.3
  });
}

// Furniture creation function
