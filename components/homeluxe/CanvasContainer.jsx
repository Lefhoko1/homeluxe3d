// Lighting setup function.
//
// There is no ground plane any more -- the lawn from blender/houseluxe is the
// ground, and a second flat plane would z-fight with it.
function setupLighting(scene, sunDirection) {
  // Sky/ground hemisphere does most of the ambient work and keeps interiors
  // from going flat grey now that the ceiling can be closed over them.
  const hemi = new THREE.HemisphereLight(0xbcd6f0, 0x6b7355, 0.85);
  scene.add(hemi);

  const ambientLight = new THREE.AmbientLight(0xffffff, 0.25);
  scene.add(ambientLight);

  // Sun, aimed along the atmosphere's sun direction so shadows fall away
  // from the bright quarter of the sky.
  const mainLight = new THREE.DirectionalLight(0xfff4e6, 2.2);
  mainLight.position.copy(sunDirection).multiplyScalar(45);
  mainLight.castShadow = true;

  // The frustum now has to cover the whole 30x40 yard, not just the house.
  // Sized too tightly, trees at the boundary stop casting entirely.
  const extent = 26;
  mainLight.shadow.camera.left = -extent;
  mainLight.shadow.camera.right = extent;
  mainLight.shadow.camera.top = extent;
  mainLight.shadow.camera.bottom = -extent;
  mainLight.shadow.camera.near = 1;
  mainLight.shadow.camera.far = 140;
  mainLight.shadow.mapSize.width = 2048;
  mainLight.shadow.mapSize.height = 2048;
  // Wider frustum means coarser texels, so the bias has to grow with it.
  mainLight.shadow.bias = -0.0009;
  mainLight.shadow.normalBias = 0.03;
  scene.add(mainLight);

  const fillLight = new THREE.DirectionalLight(0x87ceeb, 0.35);
  fillLight.position.set(-12, 8, -10);
  scene.add(fillLight);

  // Interior fills, placed just under the 2.4m ceiling in the living zone
  // and the kitchen so the inside is readable when the roof is on.
  [
    [2.7, 2.2, 2.7],
    [-0.6, 2.2, -1.6],
    [-3.5, 2.2, 3.0],
  ].forEach(([x, y, z]) => {
    const lamp = new THREE.PointLight(0xfff8dc, 8, 9);
    lamp.position.set(x, y, z);
    scene.add(lamp);
  });
}

// GLTF loading function
function loadGLTFModels(gltfModelsGroup, furniture) {
  // Use dynamic import for GLTFLoader
  import('three/examples/jsm/loaders/GLTFLoader.js').then(({ GLTFLoader }) => {
    const gltfLoader = new GLTFLoader();

    const sofaConfigs = [
      { id: 'sofa', position: { x: 0, y: 0.65, z: 2 }, rotation: Math.PI },
      { id: 'sofa2', position: { x: -3, y: 0.65, z: 1 }, rotation: Math.PI + Math.PI/4 },
      { id: 'sofa3', position: { x: 3, y: 0.65, z: 1 }, rotation: Math.PI - Math.PI/4 },
      { id: 'sofa4', position: { x: -2, y: 0.65, z: 0 }, rotation: Math.PI + Math.PI/2 }
    ];

    sofaConfigs.forEach(config => {
      gltfLoader.load(
        '/sofa.glb',
        function (gltf) {
          console.log(`Sofa model loaded successfully for ${config.id}`);
          const sofaModel = gltf.scene.clone();

          sofaModel.scale.set(2.5, 2.5, 2.5);
          sofaModel.position.set(config.position.x, config.position.y, config.position.z);
          sofaModel.rotation.y = config.rotation;

          sofaModel.traverse(function (child) {
            if (child.isMesh) {
              child.castShadow = true;
              child.receiveShadow = true;
              // Leave the original materials from the GLTF file unchanged
            }
          });

          sofaModel.userData = {
            id: config.id,
            name: 'Modern Luxury Sofa',
            clickable: true
          };

          gltfModelsGroup.add(sofaModel);

          // Hide primitive sofa parts
          furniture.children.forEach(child => {
            if (child.userData.id === config.id) {
              child.visible = false;
            }
          });

          console.log(`Sofa model added to scene for ${config.id}`);
        },
        function (xhr) {
          // xhr.total is 0 when the response has no Content-Length, which
          // made this log "Infinity% loaded" on every progress event.
          if (xhr.total > 0) {
            console.log(`${Math.round((xhr.loaded / xhr.total) * 100)}% loaded`);
          }
        },
        function (error) {
          console.error(`Error loading sofa.glb for ${config.id}:`, error);
        }
      );
    });
  }).catch(error => {
    console.error('Error loading GLTFLoader:', error);
  });
}

// TV video setup function
function setupTVVideo(furniture) {
  // Find the TV screen mesh
  const tvScreen = furniture.children.find(child => child.userData.id === 'tvScreen');
  if (!tvScreen) {
    console.error('TV screen not found');
    return;
  }

  // Create a video element
  const video = document.createElement('video');
  video.src = 'https://commondatastorage.googleapis.com/gtv-videos-bucket/sample/BigBuckBunny.mp4'; // Sample video URL
  video.crossOrigin = 'anonymous';
  video.loop = true;
  video.muted = true; // Muted to allow autoplay
  video.playsInline = true;

  // Create video texture
  const videoTexture = new THREE.VideoTexture(video);
  videoTexture.minFilter = THREE.LinearFilter;
  videoTexture.magFilter = THREE.LinearFilter;
  videoTexture.format = THREE.RGBFormat;

  // Update the TV screen material to use the video texture
  tvScreen.material = new THREE.MeshStandardMaterial({
    map: videoTexture,
    roughness: 0.1
  });

  // Start playing the video when it's loaded
  video.addEventListener('loadeddata', () => {
    video.play().catch(error => {
      console.error('Error playing video:', error);
    });
  });

  // Handle video loading errors
  video.addEventListener('error', (error) => {
    console.error('Error loading video:', error);
  });
}

